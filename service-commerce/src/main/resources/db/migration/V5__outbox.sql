-- V5__outbox.sql — service-commerce
--
-- The transactional outbox, the same table as service-player's. The insert
-- happens in the transaction that creates the purchase, so the purchase and
-- the intent to publish purchase.created commit together or not at all.
-- =============================================================================

CREATE TABLE outbox (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id     uuid NOT NULL DEFAULT gen_random_uuid(),
    event_type    varchar(100) NOT NULL,
    event_version integer NOT NULL,
    aggregate_id  uuid NOT NULL,
    payload       jsonb NOT NULL,
    published_at  timestamp(6) with time zone,
    created_at    timestamp(6) with time zone NOT NULL,
    updated_at    timestamp(6) with time zone NOT NULL,
    created_by    uuid NOT NULL,
    updated_by    uuid NOT NULL,

    CONSTRAINT outbox_pkey PRIMARY KEY (id),
    CONSTRAINT uq_outbox_public_id UNIQUE (public_id)
);

-- Serves: SELECT ... WHERE published_at IS NULL ORDER BY id FOR UPDATE SKIP LOCKED
CREATE INDEX idx_outbox_pending ON outbox (id) WHERE published_at IS NULL;
