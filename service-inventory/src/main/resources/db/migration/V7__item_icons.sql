-- =============================================================================
-- V7__item_icons.sql — service-inventory
--
-- item_icons holds each uploaded image once, under the SHA-256 of its bytes.
-- An icon's URL carries that hash, so a client caches it until the template
-- points at another icon (docs/design/inventory-design.md, Icons and names).
-- A template may have no icon, and a client then shows a generic one.
-- =============================================================================

CREATE TABLE item_icons (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id    uuid NOT NULL DEFAULT gen_random_uuid(),
    hash         varchar(64) NOT NULL,
    content_type varchar(20) NOT NULL,
    data         bytea NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    updated_at   timestamp(6) with time zone NOT NULL,
    created_by   uuid NOT NULL,
    updated_by   uuid NOT NULL,

    CONSTRAINT item_icons_pkey PRIMARY KEY (id),
    CONSTRAINT uq_item_icons_public_id UNIQUE (public_id),
    CONSTRAINT uq_item_icons_hash UNIQUE (hash),
    CONSTRAINT ck_item_icons_content_type CHECK (content_type IN ('image/png', 'image/webp'))
);

ALTER TABLE item_templates
    ADD COLUMN icon_hash varchar(64),
    ADD CONSTRAINT fk_item_templates_icon FOREIGN KEY (icon_hash) REFERENCES item_icons (hash);
