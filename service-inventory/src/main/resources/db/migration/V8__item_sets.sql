-- =============================================================================
-- V8__item_sets.sql — service-inventory
--
-- An item set, such as IRON_SET, gives its bonus to a character that has
-- every template of the set equipped. The bonus is computed at read time and
-- never stored on a character (docs/design/pathway.md). A template belongs to
-- one set at most.
-- =============================================================================

CREATE TABLE item_sets (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id  uuid NOT NULL DEFAULT gen_random_uuid(),
    code       varchar(100) NOT NULL,
    name       varchar(100) NOT NULL,
    bonus      jsonb NOT NULL,
    version    integer NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    created_by uuid NOT NULL,
    updated_by uuid NOT NULL,

    CONSTRAINT item_sets_pkey PRIMARY KEY (id),
    CONSTRAINT uq_item_sets_public_id UNIQUE (public_id),
    CONSTRAINT uq_item_sets_code UNIQUE (code)
);

ALTER TABLE item_templates
    ADD COLUMN item_set_id bigint,
    ADD CONSTRAINT fk_item_templates_item_set FOREIGN KEY (item_set_id) REFERENCES item_sets (id);

-- Serves: the templates of one set, which a set bonus reads.
CREATE INDEX idx_item_templates_item_set ON item_templates (item_set_id);
