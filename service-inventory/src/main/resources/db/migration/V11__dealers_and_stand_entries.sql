-- =============================================================================
-- V11__dealers_and_stand_entries.sql — service-inventory
--
-- An NPC dealer has a stable code, because the Unity town finds its stand by
-- it, and is retired, never deleted. A stand entry is a template and a rarity.
-- A bonus makes it a custom entry, whose every copy carries that bonus, and
-- without one each copy rolls its own (docs/design/inventory-design.md, Prices).
-- =============================================================================

CREATE TABLE dealers (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id  uuid NOT NULL DEFAULT gen_random_uuid(),
    code       varchar(100) NOT NULL,
    name       varchar(100) NOT NULL,
    retired    boolean NOT NULL,
    version    integer NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    created_by uuid NOT NULL,
    updated_by uuid NOT NULL,

    CONSTRAINT dealers_pkey PRIMARY KEY (id),
    CONSTRAINT uq_dealers_public_id UNIQUE (public_id),
    CONSTRAINT uq_dealers_code UNIQUE (code)
);

CREATE TABLE stand_entries (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id   uuid NOT NULL DEFAULT gen_random_uuid(),
    dealer_id   bigint NOT NULL,
    template_id bigint NOT NULL,
    rarity      varchar(10) NOT NULL,
    bonus       jsonb,
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone NOT NULL,
    created_by  uuid NOT NULL,
    updated_by  uuid NOT NULL,

    CONSTRAINT stand_entries_pkey PRIMARY KEY (id),
    CONSTRAINT uq_stand_entries_public_id UNIQUE (public_id),
    CONSTRAINT fk_stand_entries_dealer FOREIGN KEY (dealer_id) REFERENCES dealers (id),
    CONSTRAINT fk_stand_entries_template FOREIGN KEY (template_id) REFERENCES item_templates (id),
    CONSTRAINT ck_stand_entries_rarity
        CHECK (rarity IN ('GRAY', 'GREEN', 'BLUE', 'PURPLE', 'ORANGE', 'RED'))
);

-- Serves: a dealer's stand.
CREATE INDEX idx_stand_entries_dealer ON stand_entries (dealer_id);
