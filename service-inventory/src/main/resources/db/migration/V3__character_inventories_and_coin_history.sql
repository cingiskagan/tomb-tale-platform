-- =============================================================================
-- V3__character_inventories_and_coin_history.sql — service-inventory
--
-- character_inventories holds one row per character, made from player.created.
-- Its public_id is the character's, and player_id is its owner's. Characters
-- made before this migration get no row, so the local database starts over.
--
-- coin_history holds one row per coin change, written in the same transaction.
-- A reference, such as a trade id, is unique per character, so a change sent
-- twice finds the first one (docs/design/inventory-design.md, Coins).
-- =============================================================================

CREATE TABLE character_inventories (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id  uuid NOT NULL DEFAULT gen_random_uuid(),
    player_id  uuid NOT NULL,
    coins      bigint NOT NULL,
    version    integer NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    created_by uuid NOT NULL,
    updated_by uuid NOT NULL,

    CONSTRAINT character_inventories_pkey PRIMARY KEY (id),
    CONSTRAINT uq_character_inventories_public_id UNIQUE (public_id),
    CONSTRAINT ck_character_inventories_coins CHECK (coins >= 0)
);

CREATE TABLE coin_history (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id              uuid NOT NULL DEFAULT gen_random_uuid(),
    character_inventory_id bigint NOT NULL,
    amount                 bigint NOT NULL,
    reason                 varchar(30) NOT NULL,
    reference              uuid NOT NULL,
    created_at             timestamp(6) with time zone NOT NULL,
    updated_at             timestamp(6) with time zone NOT NULL,
    created_by             uuid NOT NULL,
    updated_by             uuid NOT NULL,

    CONSTRAINT coin_history_pkey PRIMARY KEY (id),
    CONSTRAINT uq_coin_history_public_id UNIQUE (public_id),
    CONSTRAINT fk_coin_history_character_inventory
        FOREIGN KEY (character_inventory_id) REFERENCES character_inventories (id),
    CONSTRAINT uq_coin_history_character_reference UNIQUE (character_inventory_id, reference),
    CONSTRAINT ck_coin_history_reason CHECK (reason IN ('STARTING_COINS'))
);
