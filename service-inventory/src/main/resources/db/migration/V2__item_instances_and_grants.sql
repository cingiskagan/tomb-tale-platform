-- =============================================================================
-- V2__item_instances_and_grants.sql — service-inventory
--
-- item_instances holds the stacks players own. A row is one stack, filled up
-- to its template's max_stack_size (docs/design/data-store-research.md).
--
-- item_grants holds inventory's one item grant for each purchase. The unique
-- purchase_id makes a redelivered purchase find its first item grant, so the
-- items are added once and the same item grant goes out again (ADR 0027).
-- =============================================================================

CREATE TABLE item_instances (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id   uuid NOT NULL DEFAULT gen_random_uuid(),
    player_id   uuid NOT NULL,
    template_id bigint NOT NULL,
    quantity    integer NOT NULL,
    version     integer NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone NOT NULL,
    created_by  uuid NOT NULL,
    updated_by  uuid NOT NULL,

    CONSTRAINT item_instances_pkey PRIMARY KEY (id),
    CONSTRAINT uq_item_instances_public_id UNIQUE (public_id),
    CONSTRAINT fk_item_instances_template FOREIGN KEY (template_id) REFERENCES item_templates (id),
    CONSTRAINT ck_item_instances_quantity CHECK (quantity > 0)
);

-- Serves: a player's stacks of one template, which every item grant reads.
CREATE INDEX idx_item_instances_player_template ON item_instances (player_id, template_id);

CREATE TABLE item_grants (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id   uuid NOT NULL DEFAULT gen_random_uuid(),
    purchase_id uuid NOT NULL,
    player_id   uuid NOT NULL,
    item_code   varchar(100) NOT NULL,
    quantity    integer NOT NULL,
    outcome     varchar(20) NOT NULL,
    reason      varchar(50),
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone NOT NULL,
    created_by  uuid NOT NULL,
    updated_by  uuid NOT NULL,

    CONSTRAINT item_grants_pkey PRIMARY KEY (id),
    CONSTRAINT uq_item_grants_public_id UNIQUE (public_id),
    CONSTRAINT uq_item_grants_purchase_id UNIQUE (purchase_id),
    CONSTRAINT ck_item_grants_outcome CHECK (outcome IN ('GRANTED', 'REJECTED'))
);
