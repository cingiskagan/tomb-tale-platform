CREATE TABLE item_templates (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id      uuid NOT NULL DEFAULT gen_random_uuid(),
    code           varchar(100) NOT NULL,
    max_stack_size integer NOT NULL,
    created_at     timestamp(6) with time zone NOT NULL,
    updated_at     timestamp(6) with time zone NOT NULL,
    created_by     uuid NOT NULL,
    updated_by     uuid NOT NULL,

    CONSTRAINT item_templates_pkey PRIMARY KEY (id),
    CONSTRAINT uq_item_templates_public_id UNIQUE (public_id),
    CONSTRAINT uq_item_templates_code UNIQUE (code),
    CONSTRAINT ck_item_templates_max_stack_size CHECK (max_stack_size >= 1)
);
